//! FOAR compiler: .foar source -> JSON program (consumed by web/foar-runtime.js)
//! or a ready-to-import JS module. Builds natively and for wasm32.
pub mod ast;
pub mod css;
pub mod fmt;
pub mod i18n;
pub mod lexer;
#[cfg(not(target_arch = "wasm32"))]
pub mod lsp;
pub mod parser;
pub mod project;
pub mod transpile;
pub mod typecheck;
#[cfg(target_arch = "wasm32")]
pub mod wasm;

pub use parser::CompileError;

pub fn version() -> &'static str {
    env!("CARGO_PKG_VERSION")
}

pub fn compile(src: &str) -> Result<ast::Program, CompileError> {
    parser::Parser::new(src)?.parse_program()
}

/// Program JSON, or `{"error":{"message","line","col"}}`.
pub fn compile_to_json(src: &str, pretty: bool) -> String {
    match compile(src) {
        Ok(p) => {
            if pretty { serde_json::to_string_pretty(&p).unwrap() } else { serde_json::to_string(&p).unwrap() }
        }
        Err(e) => serde_json::json!({ "error": e }).to_string(),
    }
}

/// An ES module that mounts, hydrates, or server-renders the program with the runtime.
pub fn compile_to_js_module(src: &str, runtime_path: &str) -> Result<String, CompileError> {
    Ok(program_to_js_module(&compile(src)?, runtime_path))
}

pub fn program_to_js_module(p: &ast::Program, runtime_path: &str) -> String {
    format!(
        "// Generated by foar {} — do not edit.\nimport {{ createFoarRuntime, hydrate as hydrateRuntime, hydrateIslands as hydrateIslandsRuntime, renderToString as renderRuntimeToString, renderToStringAsync as renderRuntimeToStringAsync, renderToStream as renderRuntimeToStream, createI18n }} from {};\n\nexport {{ createI18n }};\n\nexport const program = {};\n\nexport function mount(container, callbacks = {{}}) {{\n  return createFoarRuntime(program, container, callbacks);\n}}\n\nexport function hydrate(container, callbacks = {{}}) {{\n  return hydrateRuntime(program, container, callbacks);\n}}\n\nexport function hydrateIslands(root, callbacks = {{}}) {{\n  return hydrateIslandsRuntime(root, program, callbacks);\n}}\n\nexport function renderToString(options = {{}}) {{\n  return renderRuntimeToString(program, options);\n}}\n\nexport function renderToStringAsync(options = {{}}) {{\n  return renderRuntimeToStringAsync(program, options);\n}}\n\nexport function renderToStream(options = {{}}) {{\n  return renderRuntimeToStream(program, options);\n}}\n",
        version(),
        serde_json::to_string(runtime_path).unwrap(),
        serde_json::to_string_pretty(p).unwrap()
    )
}
